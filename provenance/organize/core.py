#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Provenance organize — classify inbox conversations into categories and write a
machine catalog (00_catalog.csv) + human index (00_index.md). Non-destructive.

Usage:
    prov-organize                  # data_root()/inbox -> data_root()/output
    prov-organize <inbox> <out>    # custom dirs (isolated self-tests)
    python -m provenance.organize.core [...]
"""
import csv
import json
import sys
from datetime import datetime
from pathlib import Path

from provenance import common as C


def main():
    C.cli_help(__doc__)
    root = C.data_root()
    inbox = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else root / "inbox"
    out = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else root / "output"
    if not inbox.exists():
        print(f"No inbox at {inbox}. Run ingest first.")
        return
    cats, label, order = C.load_categories()

    rows = []
    for jf in sorted(inbox.glob("*/*.json")):
        if jf.name.startswith("_"):
            continue
        try:
            obj = json.loads(jf.read_text(encoding="utf-8"))
        except Exception:
            continue
        m = C.extract_meta(obj, jf.parent.name, jf.stem)
        m["cat_id"], m["cat_label"] = C.classify_with_fallback(
            f"{m['title']} {m['first_user']}", m["source"], cats, label)
        m["file"] = str(jf.relative_to(root)).replace("\\", "/") if root in jf.parents else str(jf)
        rows.append(m)

    out.mkdir(parents=True, exist_ok=True)
    with (out / "00_catalog.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["date", "source", "cat_id", "cat_label", "title", "model",
                    "node_count", "conversation_id", "file", "attachments"])
        for m in sorted(rows, key=lambda r: (r["cat_id"], r["date"])):
            w.writerow([m["date"], m["source"], m["cat_id"], m["cat_label"], m["title"],
                        m["model"], m["node_count"], m["conversation_id"], m["file"],
                        ";".join(m.get("attachments", []))])

    lines = ["# Provenance - Conversation Index", "",
             f"> Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}  |  Total: {len(rows)} conversations",
             "> Auto-generated by provenance.organize from inbox (non-destructive; re-runnable).", ""]
    by_cat = {}
    for m in rows:
        by_cat.setdefault(m["cat_id"], []).append(m)
    for cid in order:
        items = by_cat.get(cid, [])
        if not items:
            continue
        lines += [f"## {cid} {label.get(cid, cid)} ({len(items)})", "",
                  "| Date | Source | Title |", "|------|--------|-------|"]
        for m in sorted(items, key=lambda r: r["date"]):
            title = (m["title"] or "").replace("|", "/")
            att = m.get("attachments", [])
            tail = ""
            if att:
                links = " ".join(f"[{a}](<../inbox/{m['source']}/_assets/{a}>)" for a in att[:6])
                tail = f" 📎{len(att)} {links}"
            lines.append(f"| {m['date']} | {m['source']} | [{title}](<../{m['file']}>){tail} |")
        lines.append("")
    (out / "00_index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    counts = {}
    for m in rows:
        counts[m["cat_id"]] = counts.get(m["cat_id"], 0) + 1
    print(f"Indexed {len(rows)} conversations from {inbox}")
    for cid in order:
        if counts.get(cid):
            print(f"  {cid} {label.get(cid, cid)}: {counts[cid]}")
    print(f"-> {out / '00_index.md'}")
    print(f"-> {out / '00_catalog.csv'}")


if __name__ == "__main__":
    main()
